def create_compliance_auditor_tools() -> list[BaseTool]:
    """Create tools for the compliance auditor critique agent."""

    @tool
    def record_audit_verdict(
        verdict: str,
        quality_score: int,
        citation_integrity: bool,
        schema_completeness: bool,
        pii_clean: bool,
        critique_notes: str,
    ) -> str:
        """Record formal audit verdict and critique summary for the orchestration pipeline."""
        status = "PASSED" if (citation_integrity and schema_completeness and pii_clean) else "REMEDIATION_REQUIRED"
        return (
            f"Audit verdict recorded: {verdict.upper()} [{status}]. "
            f"Score: {quality_score}/100. PII Clean: {pii_clean}. Notes: {critique_notes[:200]}"
        )

    return [record_audit_verdict]


def get_compliance_auditor_subagent(
    tools: Sequence[BaseTool | Any] | None = None,
) -> SubAgent:
    """Build the compliance-auditor SubAgent specification for create_deep_agent."""
    subagent_tools: list[Any] = (
        list(tools) if tools else create_compliance_auditor_tools()
    )

    # Restrict file write operations on the auditor (read-only enforcement)
    permissions: list[FilesystemPermission] = [
        FilesystemPermission(
            operations=["write"],
            paths=["/workspace/*", "/*"],
            mode="deny",
        )
    ]

    return {
        "name": "compliance-auditor",
        "description": (
            "Read-only critique and quality assurance subagent that verifies citation URLs, "
            "schema completeness, factual grounding, and ensures zero leaked PII across all workspace artifacts."
        ),
        "system_prompt": COMPLIANCE_AUDITOR_SYSTEM_PROMPT,
        "tools": subagent_tools,
        "permissions": permissions,
        "mode": "isolated",
    }
